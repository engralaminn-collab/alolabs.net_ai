// ─── Implementation ─────────────────────────────────────────────

export class DepartmentRegistryImpl implements DepartmentRegistry {
  private departments: Map<string, DepartmentConfig>;
  private codeIndex: Map<string, string>; // code → departmentId
  private groupIndex: Map<string, string[]>; // group → departmentId[]
  private agentIndex: Map<string, string>; // agentId → departmentId

  constructor(initialData?: DepartmentConfig[]) {
    this.departments = new Map();
    this.codeIndex = new Map();
    this.groupIndex = new Map();
    this.agentIndex = new Map();

    const data = initialData ?? INITIAL_DEPARTMENTS;
    for (const dept of data) {
      this.addDepartment(dept);
    }
  }

  getDepartment(id: string): DepartmentConfig | undefined {
    return this.departments.get(id);
  }

  getDepartmentByCode(code: string): DepartmentConfig | undefined {
    const deptId = this.codeIndex.get(code);
    if (!deptId) return undefined;
    return this.departments.get(deptId);
  }

  getDepartmentsByGroup(group: string): DepartmentConfig[] {
    const ids = this.groupIndex.get(group) ?? [];
    return ids
      .map((id) => this.departments.get(id))
      .filter((d): d is DepartmentConfig => d !== undefined);
  }

  getAllDepartments(): DepartmentConfig[] {
    return Array.from(this.departments.values());
  }

  getActiveDepartments(): DepartmentConfig[] {
    return this.getAllDepartments().filter((d) => d.status === 'active');
  }

  addDepartment(dept: DepartmentConfig): void {
    this.departments.set(dept.departmentId, dept);
    this.codeIndex.set(dept.departmentCode, dept.departmentId);

    // Update group index
    const existing = this.groupIndex.get(dept.group) ?? [];
    if (!existing.includes(dept.departmentId)) {
      existing.push(dept.departmentId);
    }
    this.groupIndex.set(dept.group, existing);

    // Update agent index
    const allAgentIds = [
      dept.directorAgentId,
      ...dept.managerAgentIds,
      ...dept.specialistAgentIds,
      ...dept.workerAgentIds,
    ].filter(Boolean);
    for (const agentId of allAgentIds) {
      this.agentIndex.set(agentId, dept.departmentId);
    }
  }

  updateDepartment(id: string, updates: Partial<DepartmentConfig>): void {
    const existing = this.departments.get(id);
    if (!existing) return;

    // If code changed, update code index
    if (updates.departmentCode && updates.departmentCode !== existing.departmentCode) {
      this.codeIndex.delete(existing.departmentCode);
      this.codeIndex.set(updates.departmentCode, id);
    }

    // If group changed, update group index
    if (updates.group && updates.group !== existing.group) {
      const oldGroup = this.groupIndex.get(existing.group) ?? [];
      this.groupIndex.set(
        existing.group,
        oldGroup.filter((gid) => gid !== id),
      );
      const newGroup = this.groupIndex.get(updates.group) ?? [];
      newGroup.push(id);
      this.groupIndex.set(updates.group, newGroup);
    }

    // Remove old agent index entries
    const oldAgentIds = [
      existing.directorAgentId,
      ...existing.managerAgentIds,
      ...existing.specialistAgentIds,
      ...existing.workerAgentIds,
    ].filter(Boolean);
    for (const agentId of oldAgentIds) {
      this.agentIndex.delete(agentId);
    }

    // Merge and store
    const updated = { ...existing, ...updates };
    this.departments.set(id, updated);

    // Add new agent index entries
    const newAgentIds = [
      updated.directorAgentId,
      ...updated.managerAgentIds,
      ...updated.specialistAgentIds,
      ...updated.workerAgentIds,
    ].filter(Boolean);
    for (const agentId of newAgentIds) {
      this.agentIndex.set(agentId, id);
    }
  }

  getDepartmentForAgent(agentId: string): DepartmentConfig | undefined {
    const deptId = this.agentIndex.get(agentId);
    if (!deptId) return undefined;
    return this.departments.get(deptId);
  }

  // ─── Convenience helpers not in interface ─────────────────────

  getGroups(): string[] {
    return Array.from(this.groupIndex.keys());
  }

  getGroupCount(group: string): number {
    return (this.groupIndex.get(group) ?? []).length;
  }

  getTotalAgentCount(): number {
    return this.getAllDepartments().reduce((sum, d) => sum + d.agentCount, 0);
  }

  getDepartmentCount(): number {
    return this.departments.size;
  }
}
