#!/usr/bin/env node
/**
 * sync-diagram-icons.mjs
 *
 * Imports the monochrome icon set from the diagram design system (cathrynlavery/diagram-design,
 * MIT; Tabler Icons MIT; Simple Icons CC0; log-z/logos MIT; Devicon MIT) by parsing the
 * `primitive-icons.md` reference. Each `### name` heading holds one SVG snippet with its own viewBox.
 *
 * Output (generated — do not hand-edit):
 *   src/lib/diagram-design/icons.generated.ts
 *
 * Usage:
 *   node scripts/sync-diagram-icons.mjs                          # clone from GitHub
 *   DIAGRAM_SRC=/path/to/checkout node scripts/sync-diagram-icons.mjs
 */

import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO = 'https://github.com/cathrynlavery/diagram-design.git'
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'src/lib/diagram-design/icons.generated.ts')

function resolveSource() {
  const local = process.env.DIAGRAM_SRC
  if (local && existsSync(local)) return { dir: local, temp: false }
  const dir = mkdtempSync(join(tmpdir(), 'diagram-design-'))
  execFileSync('git', ['clone', '--depth', '1', '-q', REPO, dir], { stdio: 'inherit' })
  return { dir, temp: true }
}

function parse(md) {
  const text = md.replace(/\r\n?/g, '\n')
  const icons = []
  let category = ''
  const blocks = text.split(/\n(?=#{2,3} )/)
  for (const block of blocks) {
    const heading = block.match(/^(#{2,3}) (.+)$/m)
    if (!heading) continue
    if (heading[1] === '##') {
      category = heading[2].trim()
      continue
    }
    const name = heading[2].trim()
    const svg = block.match(/```svg\n([\s\S]*?)```/)
    if (!svg) continue
    // Normalise the opening tag: drop the fixed 24px width/height so the renderer sizes each icon.
    // Keep the icon's own viewBox (brand marks use 100×100, 128×128, etc.).
    const markup = svg[1].trim().replace(/^(<svg\b[^>]*?)>/, (_m, open) =>
      `${open.replace(/\s(width|height)="[^"]*"/g, '')}>`,
    )
    const source = block.match(/^Source:\s*(.+)$/m)?.[1]?.trim() ?? ''
    const description = block
      .split('\n')
      .slice(1)
      .find((l) => l.trim() && !l.startsWith('```') && !l.startsWith('Source:') && !l.startsWith('<svg'))
    if (!/^<svg\b[^>]*\sviewBox="[^"]+"/.test(markup)) continue
    icons.push({ name, category, description: (description ?? '').trim(), source, markup })
  }
  return icons
}

function main() {
  const { dir, temp } = resolveSource()
  try {
    const md = readFileSync(join(dir, 'skills/diagram-design/references/primitive-icons.md'), 'utf8')
    const icons = parse(md)
    if (icons.length < 80) throw new Error(`expected ~87 icons, parsed ${icons.length}`)
    const names = new Set(icons.map((i) => i.name))
    if (names.size !== icons.length) throw new Error('duplicate icon names in upstream reference')
    const body = JSON.stringify(icons, null, 2)
    writeFileSync(
      OUT,
      `// GENERATED by scripts/sync-diagram-icons.mjs — do not edit by hand.\n// Source: ${REPO} (MIT; Tabler MIT, Simple Icons CC0, log-z MIT, Devicon MIT — see upstream THIRD_PARTY_LICENSES.md).\n\nexport interface DiagramIcon {\n  name: string\n  category: string\n  description: string\n  source: string\n  /** Full <svg> snippet with its own viewBox (no fixed width/height); uses currentColor. Trusted: generated from the upstream reference. */\n  markup: string\n}\n\nexport const DIAGRAM_ICONS: DiagramIcon[] = ${body}\n`,
    )
    console.log(`✓ ${icons.length} icons → ${OUT.replace(ROOT + '/', '')}`)
  } finally {
    if (temp) rmSync(dir, { recursive: true, force: true })
  }
}

main()
